/*
 * cp437utf8.c: CP437 to UTF-8 conversion for terminals that do not
 * natively support the IBM PC character set (OEM-US / CP437).
 *
 * The glyphs used by BitchX's ANSI art (box drawing, half blocks, shade
 * characters, greek letters, ...) are raw single byte CP437 characters.
 * On a UTF-8 terminal those bytes are meaningless, so - like the cp437(1)
 * wrapper - we detect the terminal's character set and, when it is not
 * CP437, expand each CP437 byte into the equivalent UTF-8 sequence.
 */

#include "irc.h"

#include <locale.h>
#include <langinfo.h>
#include <strings.h>

#include "cp437utf8.h"

/* 1 if the terminal speaks CP437 natively and needs no translation. */
static int terminal_supports_cp437 = 1;

/* Unicode code point for each CP437 byte in the range 0x80-0xFF. */
static const unsigned short cp437_to_unicode[128] =
{
	0x00C7, 0x00FC, 0x00E9, 0x00E2, 0x00E4, 0x00E0, 0x00E5, 0x00E7,	/* 0x80-0x87 */
	0x00EA, 0x00EB, 0x00E8, 0x00EF, 0x00EE, 0x00EC, 0x00C4, 0x00C5,	/* 0x88-0x8F */
	0x00C9, 0x00E6, 0x00C6, 0x00F4, 0x00F6, 0x00F2, 0x00FB, 0x00F9,	/* 0x90-0x97 */
	0x00FF, 0x00D6, 0x00DC, 0x00A2, 0x00A3, 0x00A5, 0x20A7, 0x0192,	/* 0x98-0x9F */
	0x00E1, 0x00ED, 0x00F3, 0x00FA, 0x00F1, 0x00D1, 0x00AA, 0x00BA,	/* 0xA0-0xA7 */
	0x00BF, 0x2310, 0x00AC, 0x00BD, 0x00BC, 0x00A1, 0x00AB, 0x00BB,	/* 0xA8-0xAF */
	0x2591, 0x2592, 0x2593, 0x2502, 0x2524, 0x2561, 0x2562, 0x2556,	/* 0xB0-0xB7 */
	0x2555, 0x2563, 0x2551, 0x2557, 0x255D, 0x255C, 0x255B, 0x2510,	/* 0xB8-0xBF */
	0x2514, 0x2534, 0x252C, 0x251C, 0x2500, 0x253C, 0x255E, 0x255F,	/* 0xC0-0xC7 */
	0x255A, 0x2554, 0x2569, 0x2566, 0x2560, 0x2550, 0x256C, 0x2567,	/* 0xC8-0xCF */
	0x2568, 0x2564, 0x2565, 0x2559, 0x2558, 0x2552, 0x2553, 0x256B,	/* 0xD0-0xD7 */
	0x256A, 0x2518, 0x250C, 0x2588, 0x2584, 0x258C, 0x2590, 0x2580,	/* 0xD8-0xDF */
	0x03B1, 0x00DF, 0x0393, 0x03C0, 0x03A3, 0x03C3, 0x00B5, 0x03C4,	/* 0xE0-0xE7 */
	0x03A6, 0x0398, 0x03A9, 0x03B4, 0x221E, 0x03C6, 0x03B5, 0x2229,	/* 0xE8-0xEF */
	0x2261, 0x00B1, 0x2265, 0x2264, 0x2320, 0x2321, 0x00F7, 0x2248,	/* 0xF0-0xF7 */
	0x00B0, 0x2219, 0x00B7, 0x221A, 0x207F, 0x00B2, 0x25A0, 0x00A0	/* 0xF8-0xFF */
};

void cp437utf8_init(void)
{
	char *codeset;

	setlocale(LC_CTYPE, "");
	codeset = nl_langinfo(CODESET);

	terminal_supports_cp437 = 0;

	if (codeset && *codeset)
	{
		/* This system uses CP437 (or an alias) natively when the
		 * codeset matches one of these.  Everything else - notably
		 * UTF-8 - needs the bytes translated. */
		if (!strcasecmp(codeset, "CP437") ||
		    !strcasecmp(codeset, "IBM437") ||
		    !strcasecmp(codeset, "PC-8") ||
		    !strcasecmp(codeset, "OEM-US") ||
		    !strcasecmp(codeset, "OEM"))
			terminal_supports_cp437 = 1;
	}
}

int cp437utf8_supported(void)
{
	return terminal_supports_cp437;
}

int cp437utf8_convert(int c, unsigned char *buf)
{
	unsigned int cp;
	int len = 1;

	if ((c & 0xFF) < 0x80)
	{
		buf[0] = (unsigned char)c;
		return 1;
	}

	cp = cp437_to_unicode[c & 0x7F];

	if (cp < 0x80)
	{
		buf[0] = (unsigned char)cp;
	}
	else if (cp < 0x800)
	{
		buf[0] = (unsigned char)(0xC0 | (cp >> 6));
		buf[1] = (unsigned char)(0x80 | (cp & 0x3F));
		len = 2;
	}
	else
	{
		buf[0] = (unsigned char)(0xE0 | (cp >> 12));
		buf[1] = (unsigned char)(0x80 | ((cp >> 6) & 0x3F));
		buf[2] = (unsigned char)(0x80 | (cp & 0x3F));
		len = 3;
	}

	buf[len] = 0;
	return len;
}